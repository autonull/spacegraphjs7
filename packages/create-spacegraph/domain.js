import fs from 'node:fs';
import path from 'node:path';

const template = (name) =>
    fs.readFileSync(new URL(`./templates/${name}`, import.meta.url), 'utf8');

const argument = process.argv[2] ?? 'my-domain';
const name = argument.replace(/^@[^/]+\//, '');
const pascal = name
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
const kind = (process.argv[3] ?? 'thing').toLowerCase();
const kinds = `${kind}s`;
const root = path.resolve(process.cwd(), name);

if (fs.existsSync(root)) {
    console.error(`Directory "${name}" already exists.`);
    process.exit(1);
}

const write = (relative, content) => {
    const file = path.join(root, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
};

const fill = (text) =>
    text
        .replaceAll('{{name}}', name)
        .replaceAll('{{Name}}', pascal)
        .replaceAll('{{Name.toUpperCase()}}', pascal.toUpperCase())
        .replaceAll('{{kind}}', kind)
        .replaceAll('{{kinds}}', kinds);

