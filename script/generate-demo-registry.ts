import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Regenerates app/demo/src/registry.ts from the demo folder tree. Run after adding, removing or
// recategorizing a demo: `pnpm exec tsx script/generate-demo-registry.ts`.

const demo = resolve(import.meta.dirname, '../app/demo');
const labels = {
    core: 'Core hosts',
    interaction: 'Interaction & navigation',
    layout: 'Layout & structure',
    rendering: 'Rendering & node types',
    plugins: 'Plugins & diagrams',
    smoke: 'Smoke & diagnostics',
} as const;

const entries = (root: string, extension: string, prefix = '', category: string = 'core') => {
    const result: string[] = [];
    for (const item of readdirSync(root, { withFileTypes: true })) {
        if (item.isDirectory()) {
            result.push(
                ...entries(
                    resolve(root, item.name),
                    extension,
                    `${prefix}${item.name}/`,
                    item.name,
                ),
            );
        } else if (item.name.endsWith(extension) && item.name !== 'index.ts') {
            const id = item.name.slice(0, -extension.length);
            result.push(
                `    { id: '${id}', category: '${category}', path: '${prefix}${item.name}' },`,
            );
        }
    }
    return result;
};

const hosts = ['index', 'showcase', 'explorer'].map(
    (id) => `    { id: '${id}', category: 'core', path: '${id}.html' },`,
);
const pages = entries(resolve(demo, 'html'), '.html', 'html/');
const modules = entries(resolve(demo, 'demos'), '.ts', 'demos/');

const source = `// Generated by script/generate-demo-registry.ts — edit the folder tree, not this file.

export const CATEGORIES = ${JSON.stringify(labels, null, 4)} as const;

export type Category = keyof typeof CATEGORIES;
export type DemoKind = 'host' | 'html' | 'module';

export interface DemoEntry {
    readonly id: string;
    readonly category: Category;
    readonly path: string;
    readonly kind: DemoKind;
}

const hosts: readonly Omit<DemoEntry, 'kind'>[] = [
${hosts.join('\n')}
];

const pages: readonly Omit<DemoEntry, 'kind'>[] = [
${pages.join('\n')}
];

const demos: readonly Omit<DemoEntry, 'kind'>[] = [
${modules.join('\n')}
];

export const DEMOS: readonly DemoEntry[] = [
    ...hosts.map((entry) => ({ ...entry, kind: 'host' as const })),
    ...pages.map((entry) => ({ ...entry, kind: 'html' as const })),
    ...demos.map((entry) => ({ ...entry, kind: 'module' as const })),
];

const byId = new Map(DEMOS.map((entry) => [entry.id, entry]));

export const demoEntry = (id: string) => byId.get(id);
export const demoPath = (id: string) => '/' + (byId.get(id)?.path ?? id + '.html');
export const demoCategory = (id: string) => byId.get(id)?.category ?? 'core';
`;

writeFileSync(resolve(demo, 'src/registry.ts'), source);
console.log(
    `registry: ${hosts.length} hosts, ${pages.length} html demos, ${modules.length} modules`,
);
